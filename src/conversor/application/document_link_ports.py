"""Porta de persistência; uso independe de JSON/PostgreSQL."""
from typing import Protocol
from conversor.domain.document_links import SnapshotVinculos, VinculoDocumental


class RepositorioVinculosDocumentais(Protocol):
    def consultar(self) -> SnapshotVinculos: ...
    def guardar_fonte(self, conteudo: bytes) -> str: ...
    def ler_fonte(self, sha256: str) -> bytes: ...
    def impressao(self, valor: str) -> str: ...
    def candidatar(self, registros: tuple[VinculoDocumental, ...], *, revisao_esperada: int,
                   responsavel: str, sessao_sha256: str) -> SnapshotVinculos: ...
    def decidir(self, id_: str, *, acao: str, revisao_esperada: int, conteudo_sha256: str,
                responsavel: str, sessao_sha256: str, fundamento: str,
                confirmar_evidencias: bool, revalidar_ate=None) -> SnapshotVinculos: ...
    def observar(self, id_: str, *, motivo: str, pendencia=None, evidencias=()) -> SnapshotVinculos: ...
    def conferir_snapshot(self, snapshot: SnapshotVinculos): ...
