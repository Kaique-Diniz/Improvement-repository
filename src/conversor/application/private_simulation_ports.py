"""Porta do armazenamento privado; casos de uso não dependem de JSON."""
from typing import Protocol

from conversor.domain.private_simulation import PacotePrivado, ExecucaoPrivada
from conversor.domain.simulation_comparison import ComparacaoPrivada
from .billing_ports import CredencialOperador


class RepositorioSimulacoes(Protocol):
    def carregar_pacote(self, id_: str) -> PacotePrivado: ...
    def carregar_execucao(self, id_: str) -> ExecucaoPrivada: ...
    def gravar_pacote(self, pacote: PacotePrivado, *, credencial: CredencialOperador) -> None: ...
    def gravar_execucao(self, execucao: ExecucaoPrivada, *, credencial: CredencialOperador) -> None: ...
    def gravar_comparacao(self, comparacao: ComparacaoPrivada, *, credencial: CredencialOperador) -> None: ...
    def carregar_comparacao(self, id_: str) -> ComparacaoPrivada: ...


class VerificadorHistoricoPlanos(Protocol):
    def conferir(self, estado) -> None: ...


class ComparadorReferencia(Protocol):
    def comparar(self, *, id_, execucao, pacote, mapeamento, template) -> ComparacaoPrivada: ...
